-- 접근 권한 없는 저장소 링크에서 보낸 공유 요청 (AC4.10).
--
-- 화면은 요청을 보낸 사람에게 「소유자에게 공유 요청을 보냈어요. 허락이 오면 알림이
-- 갑니다」라고 말한다. 그 문장이 참이려면 요청이 **어딘가에 남아** 있어야 한다 — 남지
-- 않으면 버튼은 누를 수 있지만 아무 일도 일어나지 않는 장식이고, 그것은 이 레포가
-- 편차 원장에서 이 자리를 「지어내지 않고 미룬다」로 미뤄 둔 바로 그 이유였다.
--
-- `analysis_id` 에 외래 키를 걸지 않는다. AC4.10 이 AC4.7 위에 세운 조건 때문이다 —
-- 「요청 접수의 응답과 화면은 대상이 실재하든 실재하지 않든 서로 구분되지 않는다」.
-- 외래 키를 걸면 실재하지 않는 id 의 요청만 INSERT 가 실패해, 그 실패가 응답으로
-- 새어 나가는 순간 링크 하나로 「이 id 는 존재한다」를 알아낼 수 있다. 참조 무결성을
-- 포기한 것이 아니라, 이 표의 열쇠가 **사용자가 연 링크의 문자열**이지 우리 쪽 행이
-- 아니라는 뜻이다. 그래서 대상이 나중에 지워져도 이 행은 남는다(요청은 일어났다).
--
-- `UNIQUE(analysis_id, requester_user_id)` 는 한 사람이 같은 링크로 여러 번 눌러도
-- 요청이 하나로 유지되게 한다. 화면은 누를 때마다 같은 상태로 바뀌고(응답이 갈리지
-- 않는다), 소유자는 같은 사람의 같은 요청을 여러 번 받지 않는다. 재요청의 시각을
-- 따로 적지 않는 이유는 지금 그 값을 읽는 곳이 없기 때문이다 — 통지 채널이 서는
-- 슬라이스가 필요로 하면 그때 열을 늘린다.
--
-- 소유자는 이 표에 적지 않는다. 요청을 받는 시점에 소유자를 해석하면 그 값이
-- 요청자의 경로 위에 놓이게 되고, AC4.10 이 못박은 「소유자의 신원은 요청자의
-- 화면·응답 어디에도 나타나지 않는다」를 지키기 어려워진다. 누구에게 알릴지는
-- 통지가 나가는 시점에 서버가 `analyses` 를 보고 정하면 된다.
CREATE TABLE access_requests (
    id                TEXT    PRIMARY KEY,
    analysis_id       TEXT    NOT NULL,
    requester_user_id TEXT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at        INTEGER NOT NULL,
    UNIQUE(analysis_id, requester_user_id)
);

-- 통지가 서는 시점에 「이 분석에 걸린 요청들」을 고르는 축이다.
CREATE INDEX idx_access_requests_analysis ON access_requests(analysis_id);
